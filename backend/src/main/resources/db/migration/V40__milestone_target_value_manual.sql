-- =====================================================================
-- V40: 점검 시점(마일스톤) 수치 자동 계산
--  마일스톤 수치는 기본적으로 목표의 시작값 → 목표값 직선 위에서 날짜 비율대로 서버가 계산한다.
--  사용자가 특정 시점 수치를 직접 정하면 target_value_manual = TRUE 로 두고, 자동 계산에서 건너뛴다.
--  (목표의 시작값·목표값·종료일을 바꾸면 전부 다시 자동으로 돌아간다)
--  기존 마일스톤은 모두 자동(FALSE)으로 본다.
-- =====================================================================
ALTER TABLE milestone
    ADD COLUMN target_value_manual BOOLEAN NOT NULL DEFAULT FALSE COMMENT '사용자가 수치를 직접 정했는지 (TRUE 면 자동 계산 제외)';
